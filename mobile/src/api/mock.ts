const WEEK_START = (weeksAgo: number) => {
  const d = new Date();
  const dow = d.getDay() || 7;
  d.setDate(d.getDate() - (dow - 1) - 7 * weeksAgo);
  return d.toISOString().slice(0, 10);
};

