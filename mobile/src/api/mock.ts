export async function fetchDashboard(farmId: string, date?: string): Promise<DashboardData> {
  await latency();
  const refDate = date ?? new Date().toISOString().slice(0, 10);
  const dayHash = refDate.split('-').reduce((h, v) => h * 31 + parseInt(v, 10), 0);
  const collectedVariation = Math.round(186500 + (dayHash % 40000) - 20000);
  return {
    ...DASHBOARD,
    farmId,
    generatedAt: new Date().toISOString(),
    collectedTodayFcfa: Math.max(0, collectedVariation),
  };
}

